import { api } from './client';

export const restaurantApi = {
  getFloorSnapshot: (storeId) => api.get(`/restaurant/stores/${storeId}/floor`),
  listHalls: (storeId) => api.get(`/restaurant/stores/${storeId}/halls`),
  createHall: (storeId, data) => api.post(`/restaurant/stores/${storeId}/halls`, data),
  updateHall: (hallId, data) => api.put(`/restaurant/halls/${hallId}`, data),
  deactivateHall: (hallId) => api.delete(`/restaurant/halls/${hallId}`),
  listTables: (hallId) => api.get(`/restaurant/halls/${hallId}/tables`),
  createTable: (hallId, data) => api.post(`/restaurant/halls/${hallId}/tables`, data),
  updateTable: (tableId, data) => api.put(`/restaurant/tables/${tableId}`, data),
  updateLayout: (hallId, data) => api.put(`/restaurant/halls/${hallId}/tables/layout`, data),
  deactivateTable: (tableId) => api.delete(`/restaurant/tables/${tableId}`),
  openSession: (tableId, data) => api.post(`/restaurant/tables/${tableId}/sessions`, data),
  getSession: (sessionId) => api.get(`/restaurant/sessions/${sessionId}`),
  addLine: (sessionId, data) => api.post(`/restaurant/sessions/${sessionId}/lines`, data),
  updateLine: (sessionId, lineId, data) => api.put(`/restaurant/sessions/${sessionId}/lines/${lineId}`, data),
  removeLine: (sessionId, lineId) => api.delete(`/restaurant/sessions/${sessionId}/lines/${lineId}`),
  sendToKitchen: (sessionId, department) => api.post(`/restaurant/sessions/${sessionId}/send-to-kitchen`, null, {
    params: department ? { department } : undefined,
  }),
  listKitchenTickets: (storeId, department) => api.get(`/restaurant/stores/${storeId}/kitchen/tickets`, {
    params: department ? { department } : undefined,
  }),
  listKitchenDepartments: () => api.get('/restaurant/kitchen/departments'),
  createKitchenDepartment: (data) => api.post('/restaurant/kitchen/departments', data),
  updateKitchenDepartment: (entryId, data) => api.put(`/restaurant/kitchen/departments/${entryId}`, data),
  deleteKitchenDepartment: (entryId) => api.delete(`/restaurant/kitchen/departments/${entryId}`),
  updateKitchenTicketStatus: (ticketId, status) => api.patch(`/restaurant/kitchen/tickets/${ticketId}/status`, { status }),
  checkoutPreview: (sessionId) => api.post(`/restaurant/sessions/${sessionId}/checkout-preview`),
  checkout: (sessionId, data) => api.post(`/restaurant/sessions/${sessionId}/checkout`, data),
  listReservations: (storeId, params) => api.get(`/restaurant/stores/${storeId}/reservations`, { params }),
  listBookingTables: (storeId) => api.get(`/restaurant/stores/${storeId}/booking-tables`),
  getReservation: (reservationId) => api.get(`/restaurant/reservations/${reservationId}`),
  createReservation: (storeId, data) => api.post(`/restaurant/stores/${storeId}/reservations`, data),
  updateReservation: (reservationId, data) => api.put(`/restaurant/reservations/${reservationId}`, data),
  confirmReservation: (reservationId) => api.post(`/restaurant/reservations/${reservationId}/confirm`),
  cancelReservation: (reservationId) => api.post(`/restaurant/reservations/${reservationId}/cancel`),
  noShowReservation: (reservationId) => api.post(`/restaurant/reservations/${reservationId}/no-show`),
};
